export function t(key, vars) {
  const dict = DICT[CURRENT_LANG] || DICT.ja;
  let str = dict[key] !== undefined ? dict[key] : (DICT.ja[key] !== undefined ? DICT.ja[key] : key);
  if (vars) {
    Object.keys(vars).forEach(k => { str = str.split('{' + k + '}').join(vars[k]); });
  }
  return str;
}
